// Writes every family × task workflow as a standalone ComfyUI API-format JSON file into
// workflows/<family>/<task>.json (plus one file per variant, e.g. each ControlNet type), using
// the official default file names. Drag any of them into ComfyUI to open it there.
// The engine is the source of truth: these files are generated, and tests/export.test.mjs
// fails if they no longer match what the engine builds.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildWorkflow, readInventory, FAMILIES } from "../engine/index.mjs";
import { TASKS } from "../engine/catalog.mjs";
import { variantParams } from "../engine/variants.mjs";
import { objectInfo } from "../tests/fixtures.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUT_DIR = path.join(root, "workflows");
export const EXPORT_FILES = {
  checkpoints: ["sd_xl_base_1.0.safetensors"],
  unets: ["anima-base-v1.0.safetensors", "z_image_turbo_bf16.safetensors", "krea2_turbo_fp8_scaled.safetensors"],
  loras: ["anima-turbo-lora-v0.2.safetensors", "krea2_style_reference.safetensors", "krea2/krea2_depth_control_lora.safetensors", "krea2/editor/krea2_identity_edit_v1_2.safetensors", "krea2/control/krea2_turbo_openpose_controlnet.safetensors", "krea2/krea2_unidepth_depth_exp_v1.safetensors"],
  clips: ["qwen_3_06b_base.safetensors", "qwen_3_4b.safetensors", "qwen3vl_4b_fp8_scaled.safetensors"],
  vaes: ["qwen_image_vae.safetensors", "ae.safetensors"],
  patches: ["anima-lllite-inpainting-v2.safetensors", "anima-lllite-any-test-like-v2.safetensors", "anima-lllite-depth-1.safetensors", "anima-lllite-pose-1.safetensors", "Z-Image-Turbo-Fun-Controlnet-Union-2.1-2602-8steps.safetensors"],
  controlnets: ["controlnet-union-sdxl-1.0-promax.safetensors"],
  upscalers: ["RealESRGAN_x4plus.safetensors"],
  detectors: ["bbox/face_yolov8m.pt", "bbox/hand_yolov8s.pt"],
  inputs: ["input.png"],
};

// Every exported file (relative path → text), README.md included.
export function exportAll() {
  const info = objectInfo(EXPORT_FILES);
  const ctx = { info, inv: readInventory(info) };
  const out = {};
  const rows = [];
  for (const [familyId, fam] of Object.entries(FAMILIES)) {
    for (const [taskId, task] of Object.entries(fam.tasks)) {
      if (task.unavailable) {
        rows.push({ familyId, taskId, file: "—", nodes: "not offered: " + task.unavailable.split(":")[0].replace("Not offered for Anima", "photo face-swap models do not detect anime faces") });
        continue;
      }
      for (const v of variantParams(familyId, taskId, task)) {
        const { prompt } = buildWorkflow(familyId, taskId, v.params, ctx);
        const name = v.file ? `${taskId}-${v.file}.json` : `${taskId}.json`;
        out[`${familyId}/${name}`] = JSON.stringify(prompt, null, 2) + "\n";
        const key = [...new Set(Object.values(prompt).map((n) => n.class_type))].filter((t) => !["LoadImage", "SaveImage", "VAEDecode", "VAEEncode", "CLIPTextEncode", "ImageToMask"].includes(t));
        rows.push({ familyId, taskId: v.label ? `${taskId} (${v.label})` : taskId, file: `${familyId}/${name}`, nodes: key.join(", ") });
      }
    }
  }
  const label = (f) => FAMILIES[f].label;
  const md = [
    "# Exported workflows",
    "",
    "Generated by `npm run export-workflows` from the same code the app runs. Each file is a standalone",
    "ComfyUI **API-format** workflow: drag it into ComfyUI (or load it with *Workflow → Open*).",
    "",
    "They use the official default file names (`anima-base-v1.0`, `sd_xl_base_1.0`, `z_image_turbo_bf16`,",
    "`krea2_turbo_fp8_scaled`, …) and the placeholder inputs `input.png`, `mask.png` and `face.png`.",
    "Inside Wire Studio the same workflows are rebuilt for every run with your own files and settings,",
    "and checked against your ComfyUI before they are queued. See `../docs/WORKFLOWS.md` for the reasoning",
    "and sources behind each one.",
    "",
    "| Family | Task | File | Key nodes |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${label(r.familyId)} | ${TASKS[r.taskId.split(" ")[0]]?.label || r.taskId}${r.taskId.includes("(") ? " " + r.taskId.slice(r.taskId.indexOf("(")) : ""} | ${r.file === "—" ? "—" : `[${r.file}](${r.file})`} | ${r.nodes} |`),
    "",
  ];
  out["README.md"] = md.join("\n");
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = exportAll();
  await fs.rm(OUT_DIR, { recursive: true, force: true });
  for (const [rel, text] of Object.entries(out)) {
    await fs.mkdir(path.dirname(path.join(OUT_DIR, rel)), { recursive: true });
    await fs.writeFile(path.join(OUT_DIR, rel), text);
  }
  console.log(`Wrote ${Object.keys(out).length - 1} workflows to ${path.relative(process.cwd(), OUT_DIR)}/`);
}
